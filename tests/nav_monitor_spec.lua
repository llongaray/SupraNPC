package.path = "42/media/lua/shared/?.lua;" .. package.path
local Monitor = require("SupraNPC/NavMonitor")
local mon = Monitor.new({stuckAfterTicks=30})
assert(mon.threshold == 30)
assert(Monitor.observe(mon, 1,1,0,0,false) == "IDLE")
assert(Monitor.observe(mon, 1,1,0,1,true) == "TRACKING")
assert(Monitor.observe(mon, 1,1,0,2,true) == "WAIT")
assert(Monitor.observe(mon, 1,1,0,31,true) == "REPATH")
assert(mon.attempts == 1)
assert(Monitor.observe(mon, 1,1,0,31,true) == "WAIT") -- mesmo tick nao duplica
assert(Monitor.observe(mon, 1,1,0,61,true) == "REPATH")
assert(Monitor.observe(mon, 1,1,0,91,true) == "BLOCKED")
assert(Monitor.observe(mon, 1,1,0,92,true) == "BLOCKED")
assert(Monitor.observe(mon, 2,1,0,93,true) == "MOVING")
assert(mon.attempts == 0)
assert(Monitor.observe(mon, 2,1,0,94,true) == "WAIT")
assert(Monitor.observe(mon, 2,1,0,125,true) == "REPATH")
assert(Monitor.observe(mon, 2,1,0,126,false) == "IDLE")
assert(mon.lastProgressTick == nil)
assert(Monitor.observe(mon, 5,5,0,1,true) == "TRACKING")
assert(Monitor.observe(mon, 5,5,0,0,true) == "TRACKING") -- tick reiniciou
assert(Monitor.observe(mon, 0/0,1,0,1,true) == nil)
assert(Monitor.observe(mon, 1,1,0,-1,true) == nil)
assert(Monitor.observe(mon, 1,1,0,1.5,true) == nil)
print("[SupraNPC] nav_monitor_spec: OK")
